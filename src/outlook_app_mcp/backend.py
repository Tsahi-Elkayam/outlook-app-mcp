"""The operations a backend provides, and how the server picks one.

Every backend drives the Outlook app installed on this computer, never a mail
server directly: Outlook for Mac (Legacy mode) through AppleScript, or classic
Outlook for Windows through COM. Ids are opaque text; each backend checks the
ids it gets and returns ids in the same form.
"""

from __future__ import annotations

import os
import sys
from collections.abc import Sequence
from typing import Protocol

from .common import OutlookError


class Backend(Protocol):
    """Every method of every backend. Arguments after the first few are keyword
    arguments in server.py, so both backends must use these exact names."""

    name: str
    description: str

    # accounts
    def list_accounts(self) -> dict: ...
    def send_and_receive(self) -> dict: ...

    # mail: read
    def list_folders(self, account: str | None = None, refresh: bool = False) -> list[dict]: ...
    def list_messages(self, folder_id=None, account=None, limit=50, unread_only=False, since_days=None,
                      offset=0) -> dict: ...
    def search(self, query="", folder_id=None, account=None, since_days=90, include_body=False, limit=50,
               from_address=None, to_address=None, has_attachments=None, flagged=None, category=None,
               after=None, before=None, offset=0) -> dict: ...
    def read_message(self, message_id: str, max_chars: int, include_headers=False, as_html=False) -> dict: ...
    def get_conversation(self, message_id: str, limit: int) -> dict: ...

    # mail: change
    def mark_messages(self, message_ids: Sequence[str], action: str, due_date=None) -> dict: ...
    def move_messages(self, message_ids: Sequence[str], folder_id: str) -> dict: ...
    def delete_messages(self, message_ids: Sequence[str]) -> dict: ...
    def create_draft(self, to=(), subject="", body="", cc=(), bcc=(), attachments=(), body_is_html=False,
                     account=None, importance=None, signature=None) -> dict: ...
    def send_message(self, to, subject, body, cc=(), bcc=(), attachments=(), body_is_html=False, account=None,
                     importance=None, signature=None) -> dict: ...
    def update_draft(self, draft_id: str, to=None, cc=None, bcc=None, subject=None, body=None,
                     body_is_html=False, add_attachments=(), remove_attachments=(), importance=None) -> dict: ...
    def send_draft(self, draft_id: str) -> dict: ...
    def reply_to_message(self, message_id: str, body: str, reply_all=False, send=False, cc=(), attachments=(),
                         signature=None) -> dict: ...
    def forward_message(self, message_id: str, to: Sequence[str], body="", send=False, cc=(), attachments=(),
                        signature=None) -> dict: ...
    def create_folder(self, name: str, parent_id: str | None, account: str | None) -> dict: ...
    def rename_folder(self, folder_id: str, name: str) -> dict: ...
    def move_folder(self, folder_id: str, parent_id: str) -> dict: ...
    def delete_folder(self, folder_id: str) -> dict: ...
    def save_attachment(self, message_id: str, attachment: str | int, dest_dir: str) -> dict: ...
    def list_signatures(self) -> dict: ...

    # categories
    def list_categories(self) -> dict: ...
    def create_category(self, name: str) -> dict: ...
    def categorize(self, item_type: str, item_ids: Sequence[str], categories: Sequence[str], mode: str) -> dict: ...

    # out of office
    def get_auto_reply(self, account: str | None) -> dict: ...
    def set_auto_reply(self, account=None, enabled=False, internal_message=None, external_message=None,
                       external_audience=None, start=None, end=None) -> dict: ...

    # calendar
    def list_calendars(self) -> list[dict]: ...
    def list_events(self, start: str | None, end: str | None, calendar_id: str | None) -> dict: ...
    def read_event(self, event_id: str, occurrence_start=None) -> dict: ...
    def create_event(self, subject, start, end, calendar_id=None, location=None, body=None, all_day=None,
                     free_busy=None, reminder_minutes=None, attendees=(), optional_attendees=(),
                     send_invitations=False, recurrence=None, categories=None, is_private=None) -> dict: ...
    def update_event(self, event_id, subject=None, start=None, end=None, location=None, body=None, all_day=None,
                     free_busy=None, reminder_minutes=None, remove_reminder=False, whole_series=False,
                     occurrence_start=None, attendees=None, optional_attendees=None, categories=None,
                     is_private=None, send_update=False) -> dict: ...
    def delete_event(self, event_id: str, whole_series=False, occurrence_start=None) -> dict: ...
    def cancel_meeting(self, event_id: str, comment="", occurrence_start=None) -> dict: ...
    def respond_to_meeting(self, event_id: str, response: str, comment: str, send_response: bool,
                           occurrence_start=None) -> dict: ...
    def get_free_busy(self, addresses: Sequence[str], start: str, end: str, interval_minutes: int) -> dict: ...

    # tasks
    def list_tasks(self, include_completed=False, query=None, due_before=None, limit=50) -> dict: ...
    def read_task(self, task_id: str) -> dict: ...
    def create_task(self, subject, body=None, due=None, start=None, reminder=None, priority=None,
                    categories=None, account=None) -> dict: ...
    def update_task(self, task_id, subject=None, body=None, due=None, start=None, reminder=None,
                    remove_reminder=False, priority=None, complete=None, categories=None) -> dict: ...
    def delete_task(self, task_id: str) -> dict: ...

    # notes
    def list_notes(self, query=None, limit=50) -> dict: ...
    def read_note(self, note_id: str) -> dict: ...
    def create_note(self, title: str, body="", account=None) -> dict: ...
    def update_note(self, note_id: str, title=None, body=None) -> dict: ...
    def delete_note(self, note_id: str) -> dict: ...

    # contacts
    def search_contacts(self, query: str, limit: int) -> dict: ...
    def read_contact(self, contact_id: str) -> dict: ...
    def lookup_directory(self, query: str, limit: int) -> dict: ...
    def create_contact(self, emails: Sequence[str] | None = None, **fields) -> dict: ...
    def update_contact(self, contact_id: str, emails: Sequence[str] | None = None, **fields) -> dict: ...
    def delete_contact(self, contact_id: str) -> dict: ...
    def list_contact_groups(self, query: str | None) -> dict: ...
    def create_contact_group(self, name: str, members: Sequence[str]) -> dict: ...
    def update_contact_group(self, group_id: str, name=None, add_members=(), remove_members=()) -> dict: ...
    def delete_contact_group(self, group_id: str) -> dict: ...


BACKENDS = ("mac", "windows")


def default_backend_name() -> str:
    chosen = os.environ.get("OUTLOOK_APP_MCP_BACKEND", "").strip().lower()
    if chosen:
        if chosen not in BACKENDS:
            raise OutlookError(f"OUTLOOK_APP_MCP_BACKEND={chosen!r}; use one of {', '.join(BACKENDS)}.")
        return chosen
    if sys.platform == "darwin":
        return "mac"
    if sys.platform == "win32":
        return "windows"
    raise OutlookError(
        f"No Outlook backend for {sys.platform}. This server drives the Outlook desktop app: "
        "Outlook for Mac (Legacy mode) or classic Outlook for Windows."
    )


def load_backend(name: str | None = None) -> Backend:
    name = name or default_backend_name()
    if name == "mac":
        from .mac import MacOutlook

        return MacOutlook()
    if name == "windows":
        from .windows import WindowsOutlook

        return WindowsOutlook()
    raise OutlookError(f"Unknown backend {name!r}; use one of {', '.join(BACKENDS)}.")
